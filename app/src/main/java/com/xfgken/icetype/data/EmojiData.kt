    private const val FILE_NAME = "emoji_recent.json"
    private const val MAX_RECENT = 36

    private var file: File? = null

    fun init(context: Context) {
        val dir = File(context.filesDir, "data").apply { mkdirs() }
        file = File(dir, FILE_NAME)
    }

    fun recent(): List<String> {
        val f = file ?: return emptyList()
        if (!f.isFile) return emptyList()
        return try {
            val array = JSONArray(f.readText())
            (0 until array.length()).map { array.optString(it) }.filter { it.isNotEmpty() }
        } catch (t: Throwable) {
            AppLog.throwable(AppLog.Category.ERROR, "读取表情最近使用失败", t)
            emptyList()
        }
    }

    fun markUsed(emoji: String) {
        val f = file ?: return
        val list = recent().toMutableList()
        list.remove(emoji)
        list.add(0, emoji)
        while (list.size > MAX_RECENT) list.removeAt(list.size - 1)
        runCatching {
            val array = JSONArray()
            list.forEach { array.put(it) }
            f.writeText(array.toString())
        }
    }

    /** 清空最近使用（传入空串即视为清空）。 */
    fun clearRecent() {
        val f = file ?: return
        runCatching { f.writeText("[]") }
    }

    /** 表情总数（不含「最近」）。 */
    fun totalCount(): Int = categories.drop(1).sumOf { it.second.size }
